"""Scenario -> static occupancy map (.pgm + .yaml), rasterised from the same
obstacle list that generates the world, so the two cannot drift apart.

An unknown margin is deliberately left around the world. A map consisting only
of free and occupied cells would delete a large part of Smac's real behaviour:
`allow_unknown: true` and `track_unknown_space: true` mean planning through
unknown space is a code path the robot exercises constantly, and a map that is
"too perfect" would not exercise it at all.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .spec import Scenario

FREE, OCCUPIED, UNKNOWN = 254, 0, 205
DEFAULT_RESOLUTION = 0.05          # matches both nav2 costmaps
DEFAULT_MARGIN_M = 1.0             # unknown border


def rasterise(sc: Scenario, resolution: float = DEFAULT_RESOLUTION,
              margin: float = DEFAULT_MARGIN_M) -> tuple[np.ndarray, tuple[float, float]]:
    """Return (image, origin_xy). Image row 0 is y-min, matching OccupancyGrid;
    it is flipped only when written, since PGM stores the top row first."""
    w, h = sc.size
    t = sc.wall_thickness
    half_w, half_h = w / 2 + t + margin, h / 2 + t + margin
    cols = int(round(2 * half_w / resolution))
    rows = int(round(2 * half_h / resolution))
    img = np.full((rows, cols), UNKNOWN, dtype=np.uint8)
    origin = (-half_w, -half_h)

    def to_cell(x: float, y: float) -> tuple[int, int]:
        return (int((x - origin[0]) / resolution), int((y - origin[1]) / resolution))

    # interior of the world is free ...
    c0, r0 = to_cell(-w / 2, -h / 2)
    c1, r1 = to_cell(w / 2, h / 2)
    img[r0:r1, c0:c1] = FREE

    # ... then every box, walls included, is stamped occupied
    for b in sc.all_boxes:
        x0, y0, x1, y1 = b.bounds
        bc0, br0 = to_cell(x0, y0)
        bc1, br1 = to_cell(x1, y1)
        img[max(0, br0):max(0, br1), max(0, bc0):max(0, bc1)] = OCCUPIED
    return img, origin


def write(sc: Scenario, out_dir: str | Path,
          resolution: float = DEFAULT_RESOLUTION) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    img, origin = rasterise(sc, resolution)
    pgm = out_dir / f'{sc.name}.pgm'
    yml = out_dir / f'{sc.name}.yaml'

    # PGM is written top row first, so flip the y axis on the way out.
    flipped = np.flipud(img)
    with open(pgm, 'wb') as f:
        f.write(b'P5\n')
        f.write(f'# generated by picar2_benchmark from {sc.name}\n'.encode())
        f.write(f'{flipped.shape[1]} {flipped.shape[0]}\n255\n'.encode())
        f.write(flipped.tobytes())

    yml.write_text(
        f'image: {pgm.name}\n'
        f'mode: trinary\n'
        f'resolution: {resolution}\n'
        f'origin: [{origin[0]}, {origin[1]}, 0.0]\n'
        f'negate: 0\n'
        f'occupied_thresh: 0.65\n'
        f'free_thresh: 0.25\n')
    return pgm, yml
